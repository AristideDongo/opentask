export const API_PREFIX = '/api/v1';

export type HttpMethod = 'get' | 'post' | 'put' | 'patch' | 'delete';

export interface RouteContract {
  method: HttpMethod;
  path: string;
  operationId: string;
  summary: string;
  tag:
    | 'auth'
    | 'me'
    | 'workspaces'
    | 'members'
    | 'invitations'
    | 'audit'
    | 'teams'
    | 'projects'
    | 'tasks'
    | 'channels'
    | 'files'
    | 'realtime'
    | 'system';
  auth: 'session' | 'public';
  tokenAuth?: false;
  upload?: true;
  binary?: true;
  body?: z.ZodType;
  query?: z.ZodType;
  response?: z.ZodType;
  status?: number;
  external?: boolean;
}

